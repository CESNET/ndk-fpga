class trim_sequence_library #(int unsigned BLOCK_SIZE, int unsigned ITEM_WIDTH, int unsigned META_WIDTH, int unsigned PKT_MTU) extends uvm_common::sequence_library #(uvm_logic_vector::config_sequence, uvm_logic_vector::sequence_item #(META_WIDTH+1+$clog2(PKT_MTU+1)));
    `uvm_object_param_utils(test::trim_sequence_library #(BLOCK_SIZE, ITEM_WIDTH, META_WIDTH, PKT_MTU))
    `uvm_sequence_library_utils(test::trim_sequence_library #(BLOCK_SIZE, ITEM_WIDTH, META_WIDTH, PKT_MTU))

    function new(string name = "trim_sequence_library");
        super.new(name);

        init_sequence_library();
    endfunction

    virtual function void init_sequence(uvm_logic_vector::config_sequence param_cfg = null);
        super.init_sequence(param_cfg);

        this.add_sequence(trim_sequence_random_length   #(BLOCK_SIZE, ITEM_WIDTH, META_WIDTH, PKT_MTU)::get_type());
        this.add_sequence(trim_sequence_original_length #(BLOCK_SIZE, ITEM_WIDTH, META_WIDTH, PKT_MTU)::get_type());
        this.add_sequence(trim_sequence_minimal_length  #(BLOCK_SIZE, ITEM_WIDTH, META_WIDTH, PKT_MTU)::get_type());
    endfunction

endclass
