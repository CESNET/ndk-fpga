        add_sequence(extension_sequence_only     #(MFB_BLOCK_SIZE, PKT_MTU, RX_MVB_ITEM_WIDTH)::get_type());
        add_sequence(extension_sequence_only_min #(MFB_BLOCK_SIZE, PKT_MTU, RX_MVB_ITEM_WIDTH)::get_type());
        add_sequence(extension_sequence_only_max #(MFB_BLOCK_SIZE, PKT_MTU, RX_MVB_ITEM_WIDTH)::get_type());
    endfunction

endclass
