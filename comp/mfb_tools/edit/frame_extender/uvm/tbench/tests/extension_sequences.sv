    `uvm_sequence_library_utils(test::extension_sequence_library #(MFB_BLOCK_SIZE, PKT_MTU, RX_MVB_ITEM_WIDTH))

    function new(string name = "extension_sequence_library");
        super.new(name);

        init_sequence_library();
    endfunction

    function void init_sequence(uvm_logic_vector::config_sequence param_cfg = null);
