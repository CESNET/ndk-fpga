virtual class extension_sequence_base #(int unsigned MFB_BLOCK_SIZE, int unsigned PKT_MTU, int unsigned RX_MVB_ITEM_WIDTH) extends uvm_logic_vector::sequence_simple #(RX_MVB_ITEM_WIDTH);
    `uvm_object_param_utils(test::extension_sequence_base #(MFB_BLOCK_SIZE, PKT_MTU, RX_MVB_ITEM_WIDTH))
    `m_uvm_get_type_name_func(test::extension_sequence_base)

    localparam int unsigned MAX_DATA_LENGTH = PKT_MTU;
    localparam int unsigned MIN_DATA_LENGTH = 64;

    localparam int unsigned MAX_EXTENSION_ONLY_LENGTH = MAX_DATA_LENGTH - (MAX_DATA_LENGTH % MFB_BLOCK_SIZE); // The closest value divisible by MFB_BLOCK_SIZE and less than or equal to MAX_DATA_LENGTH
    localparam int unsigned MAX_EXTENSION_LENGTH      = (MAX_DATA_LENGTH-MIN_DATA_LENGTH) - ((MAX_DATA_LENGTH-MIN_DATA_LENGTH) % MFB_BLOCK_SIZE); // The closest value divisible by MFB_BLOCK_SIZE and less than or equal to (MAX_DATA_LENGTH-MIN_DATA_LENGTH)
    localparam int unsigned MIN_EXTENSION_LENGTH      = 60 - (60 % MFB_BLOCK_SIZE) + MFB_BLOCK_SIZE; // The closest value divisible by MFB_BLOCK_SIZE and greater than or equal to 60

    rand int unsigned transaction_count;

    // Stores the lengths of data frames generated by an RX MFB sequence
    mailbox #(int unsigned) frame_lengths;

    // Constructor
    function new(string name = "extension_sequence_base");
        super.new(name);
    endfunction

    // Gets a `frame_lengths` mailbox reference from the database
    function void load_from_db();
        assert(uvm_config_db #(mailbox #(int unsigned))::get(m_sequencer, "", "frame_lengths", frame_lengths))
        else begin
            `uvm_fatal(m_sequencer.get_full_name(), "\n\tCannot get the mailbox")
        end
    endfunction

    pure virtual task body;

endclass

// ------------------- //
// Extending sequences //
// ------------------- //

class extension_sequence #(int unsigned MFB_BLOCK_SIZE, int unsigned PKT_MTU, int unsigned RX_MVB_ITEM_WIDTH) extends extension_sequence_base #(MFB_BLOCK_SIZE, PKT_MTU, RX_MVB_ITEM_WIDTH);
    `uvm_object_param_utils(test::extension_sequence #(MFB_BLOCK_SIZE, PKT_MTU, RX_MVB_ITEM_WIDTH))
    `m_uvm_get_type_name_func(test::extension_sequence)

    int unsigned transaction_count_min = 15;
    int unsigned transaction_count_max = 30;

    constraint c_transaction_count { transaction_count inside { [transaction_count_min : transaction_count_max] }; }

    // Constructor
    function new(string name = "extension_sequence");
        super.new(name);
    endfunction

    // Generates transactions
    task body;
        load_from_db();

        repeat (transaction_count) begin
            int unsigned frame_length;

            frame_lengths.get(frame_length);

            if (frame_length+MIN_EXTENSION_LENGTH > PKT_MTU) begin
                `uvm_do_with(req, {
                    req.data[1-1 -: 1] == 0; // RX_MVB_EXT_EN
                    // RX_MVB_FRAME_LENGTH
                    req.data[$clog2(PKT_MTU+1)+$clog2(PKT_MTU+1)+1+1-1 -: $clog2(PKT_MTU+1)] == frame_length;
                })
            end
            else begin
                `uvm_do_with(req, {
                    req.data[1-1   -: 1] == 1; // RX_MVB_EXT_EN
                    req.data[1+1-1 -: 1] == 0; // RX_MVB_EXT_ONLY
                    // RX_MVB_EXT_SIZE
                    (req.data[$clog2(PKT_MTU+1)+1+1-1 -: $clog2(PKT_MTU+1)] % MFB_BLOCK_SIZE) == 0;     // (RX_MVB_EXT_SIZE % MFB_BLOCK_SIZE) = 0
                    req.data[$clog2(PKT_MTU+1)+1+1-1 -: $clog2(PKT_MTU+1)] >= MIN_EXTENSION_LENGTH;     // RX_MVB_EXT_SIZE >= MIN_EXTENSION_LENGTH
                    req.data[$clog2(PKT_MTU+1)+1+1-1 -: $clog2(PKT_MTU+1)] <= MAX_EXTENSION_LENGTH;     // RX_MVB_EXT_SIZE <= MAX_EXTENSION_LENGTH
                    (req.data[$clog2(PKT_MTU+1)+1+1-1 -: $clog2(PKT_MTU+1)] + frame_length) <= PKT_MTU; // RX_MVB_EXT_SIZE+frame_length <= PKT_MTU
                    // RX_MVB_FRAME_LENGTH
                    req.data[$clog2(PKT_MTU+1)+$clog2(PKT_MTU+1)+1+1-1 -: $clog2(PKT_MTU+1)] == frame_length;
                })
            end
        end
    endtask

endclass

