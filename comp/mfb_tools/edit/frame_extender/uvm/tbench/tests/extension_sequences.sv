        add_sequence(extension_sequence          #(MFB_BLOCK_SIZE, PKT_MTU, RX_MVB_ITEM_WIDTH)::get_type());
        add_sequence(extension_sequence_min      #(MFB_BLOCK_SIZE, PKT_MTU, RX_MVB_ITEM_WIDTH)::get_type());
        add_sequence(extension_sequence_max      #(MFB_BLOCK_SIZE, PKT_MTU, RX_MVB_ITEM_WIDTH)::get_type());
